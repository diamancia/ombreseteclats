export function normalizePlatformKey(value: string): SocialPlatformKey {
  const v = value.trim().toLowerCase();
  const match = SOCIAL_PLATFORMS.find((p) => p.key === v || p.label.toLowerCase() === v);
  return match ? match.key : "autre";
}

export function SocialIcon({ platform, className = "h-4 w-4" }: { platform: string; className?: string }) {
  const key = normalizePlatformKey(platform);
  if (key === "autre" || !PATHS[key]) {
    // Repli générique — lien externe, cohérent avec le reste des icônes lucide du site.
    return (
      <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" className={className} aria-hidden="true">
        <path d="M10 13a5 5 0 0 0 7.07 0l1.93-1.93a5 5 0 0 0-7.07-7.07L10.5 5.5" />
        <path d="M14 11a5 5 0 0 0-7.07 0l-1.93 1.93a5 5 0 0 0 7.07 7.07L13.5 18.5" />
      </svg>
    );
  }
  return (
    <svg viewBox="0 0 24 24" fill="currentColor" className={className} aria-hidden="true">
      <path d={PATHS[key]} />
    </svg>
  );
}
